import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { CheckCircle2, Info } from 'lucide-react';
import { FORMULAS, type Formula } from '@/content/formulas';
import { Callout, Select, Tex } from '@/components/ui';
import { PageHeader } from './shared';

/**
 * Numerical round-trip check: make the default values self-consistent using the first
 * rearrangement, then confirm every other rearrangement recovers its variable.
 */
function verify(f: Formula): Record<string, 'ok' | 'multi'> {
  const keys = Object.keys(f.solve);
  const vals: Record<string, number> = Object.fromEntries(f.vars.map((v) => [v.key, v.def]));
  vals[keys[0]] = f.solve[keys[0]].fn(vals);
  const out: Record<string, 'ok' | 'multi'> = {};
  for (const k of keys) {
    const got = f.solve[k].fn(vals);
    out[k] = Number.isFinite(got) && Math.abs(got - vals[k]) <= Math.abs(vals[k]) * 1e-6 + 1e-12 ? 'ok' : 'multi';
  }
  return out;
}

export default function Rearrange() {
  const [fid, setFid] = useState('suvat-v');
  const f = FORMULAS.find((x) => x.id === fid) ?? FORMULAS[0];
  const [target, setTarget] = useState<string>('');
  const checks = useMemo(() => verify(f), [f]);
  const keys = Object.keys(f.solve);
  const shown = target && keys.includes(target) ? [target] : keys;

  return (
    <div className="mx-auto max-w-4xl space-y-6">
      <PageHeader kicker="Formula rearrangement" title="Make any variable the subject">
        Every rearrangement here is written out and checked in advance — nothing is generated by manipulating text — and each one is verified numerically against the original formula. Notes flag multiple roots and restricted ranges.
      </PageHeader>
      <div className="card grid gap-3 p-5 sm:grid-cols-2">
        <Select label="Formula" value={f.id} options={FORMULAS.map((x) => ({ value: x.id, label: `M${x.module} · ${x.name}` }))} onChange={(v) => { setFid(v); setTarget(''); }} />
        <Select label="Make the subject" value={target} options={[{ value: '', label: 'Show all variables' }, ...keys.map((k) => ({ value: k, label: `${f.vars.find((v) => v.key === k)?.name ?? k}` }))]} onChange={setTarget} />
      </div>
      <div className="card p-6 text-center">
        <div className="label mb-2">Original</div>
        <Tex block className="text-2xl">
          {f.tex}
        </Tex>
        <Link to={`/formulas/${f.id}`} className="mt-2 inline-block text-sm text-accent hover:underline">
          Formula details and calculator →
        </Link>
      </div>
      <div className="grid gap-3 sm:grid-cols-2">
        {shown.map((k) => {
          const v = f.vars.find((x) => x.key === k)!;
          const r = f.solve[k];
          return (
            <div key={k} className="card p-5">
              <div className="flex items-center justify-between gap-2">
                <div className="text-sm">
                  Subject: <Tex>{v.symbol}</Tex> <span className="text-muted">({v.name}, {v.unit})</span>
                </div>
                {checks[k] === 'ok' ? (
                  <span className="flex items-center gap-1 text-xs text-good" title="Recovered the original value numerically">
                    <CheckCircle2 className="h-4 w-4" /> verified
                  </span>
                ) : (
                  <span className="flex items-center gap-1 text-xs text-warn" title="More than one solution is possible">
                    <Info className="h-4 w-4" /> see note
                  </span>
                )}
              </div>
              <Tex block className="my-3 text-xl">
                {r.tex}
              </Tex>
              {r.note && <p className="text-xs text-muted">{r.note}</p>}
              {checks[k] === 'multi' && !r.note && <p className="text-xs text-muted">This rearrangement returns the principal value (e.g. the acute angle); another physical solution may exist.</p>}
            </div>
          );
        })}
      </div>
      <Callout kind="tip" title="Rearranging by hand">
        <ol className="list-decimal space-y-1 pl-5">
          <li>Undo additions/subtractions first, then multiplications/divisions, then powers and roots — the reverse of the order of operations.</li>
          <li>Do the same operation to both sides at every step.</li>
          <li>For squares, the square root gives ± — choose the sign that is physical.</li>
          <li>For sin θ = x, θ = sin⁻¹ x gives the acute angle; check whether the obtuse angle (180° − θ) is also possible.</li>
          <li>Check units of the result before substituting.</li>
        </ol>
      </Callout>
    </div>
  );
}
