import { C, rad } from '@/lib/physics/constants';

export type ModuleNo = 5 | 6 | 7 | 8;

export interface FormulaVar {
  key: string;
  /** LaTeX symbol */
  symbol: string;
  name: string;
  /** SI unit (plain text) */
  unit: string;
  /** default value used to pre-fill calculators */
  def: number;
  /** quantity must be > 0 (or ≥ 0 with allowZero) */
  positive?: boolean;
  allowZero?: boolean;
  /** angle entered in degrees */
  angle?: boolean;
  integer?: boolean;
  /** quantity is signed (vector component) */
  signed?: boolean;
}

export interface Rearrangement {
  /** LaTeX of the rearranged formula, e.g. "a = \\frac{v-u}{t}" */
  tex: string;
  fn: (v: Record<string, number>) => number;
  /** caveats such as multiple roots */
  note?: string;
}

export interface Formula {
  id: string;
  name: string;
  module: ModuleNo;
  /** syllabus section id (see syllabus.ts) */
  section: string;
  tex: string;
  vars: FormulaVar[];
  solve: Record<string, Rearrangement>;
  interpretation: string;
  conditions: string[];
  /** appears on the NESA Physics formulae sheet */
  onSheet: boolean;
  /** Year 11 prerequisite relationship used in Year 12 */
  prereq?: boolean;
  /** beyond the formula sheet / syllabus — supplementary support */
  supplementary?: boolean;
  example: { q: string; steps: string[]; answer: string };
  errors: string[];
  practice: { q: string; answer: number; unit: string; tol?: number; solution: string };
  /** physical-reasonableness checks given the full set of values */
  sanity?: (v: Record<string, number>) => string | null;
}

const S = (d: number) => Math.sin(rad(d));
const Co = (d: number) => Math.cos(rad(d));
const asinD = (x: number) => (Math.abs(x) > 1 + 1e-12 ? NaN : (Math.asin(Math.max(-1, Math.min(1, x))) * 180) / Math.PI);
const acosD = (x: number) => (Math.abs(x) > 1 + 1e-12 ? NaN : (Math.acos(Math.max(-1, Math.min(1, x))) * 180) / Math.PI);
const atanD = (x: number) => (Math.atan(x) * 180) / Math.PI;
const sqrtP = (x: number) => (x < 0 ? NaN : Math.sqrt(x));

const tooFast = (v: Record<string, number>, k = 'v') => (Math.abs(v[k]) >= C.c ? 'A speed ≥ c is impossible for a massive object.' : null);

