export const formulaById = (id: string) => FORMULAS.find((f) => f.id === id);

/** Generic sanity checks applied in the calculator UI. */
export function genericChecks(f: Formula, values: Record<string, number>, unknown: string): string[] {
  const out: string[] = [];
  const val = values[unknown];
  if (!Number.isFinite(val)) {
    out.push('No real, physical solution for these inputs (e.g. a square root of a negative number, sin θ > 1, or division by zero). Check the inputs.');
    return out;
  }
  for (const vdef of f.vars) {
    const x = values[vdef.key];
    if (vdef.positive && (vdef.allowZero ? x < 0 : x <= 0)) out.push(`${vdef.name} should be ${vdef.allowZero ? 'zero or positive' : 'positive'} — result is not physical.`);
    if (vdef.integer && vdef.key === unknown && Math.abs(x - Math.round(x)) > 0.05) out.push(`${vdef.name} should be a whole number — the inputs are inconsistent (nearest integer ${Math.round(x)}).`);
    if (vdef.angle && vdef.key === unknown && (x < 0 || x > 180)) out.push('Angle outside 0–180°.');
  }
  const s = f.sanity?.(values);
  if (s) out.push(s);
  return out;
}

